#!/bin/bash

set -euo pipefail

source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/base-test.sh"

authorize="$ROOT/bin/omarchy-hw-egpu-authorize"
enclosures="$ROOT/default/egpu/enclosures.tsv"
gpus="$ROOT/default/egpu/gpus.tsv"
rule="$ROOT/default/udev/90-omarchy-egpu.rules"
migration="$ROOT/migrations/1790804830.sh"

grep -Fq $'0x0041\t0x0308\tinXtron\tAKiTiO Node\tverified' "$enclosures" ||
  fail "the verified AKiTiO enclosure is catalogued by Thunderbolt identity"
grep -Fq $'0x1002\t0x73ff\tAMD\tNavi 23' "$gpus" ||
  fail "the verified RX 6600 family is catalogued by PCI identity"
grep -Eq $'0x1002\t.*\tamdgpu\t' "$gpus" || fail "the GPU catalog includes amdgpu cards"
grep -Eq $'0x8086\t.*\txe/i915\t' "$gpus" || fail "the GPU catalog includes Intel cards"
grep -Eq $'0x10de\t.*\tnouveau/nvidia\t' "$gpus" || fail "the GPU catalog includes NVIDIA cards"
pass "eGPU compatibility catalogs cover enclosure identities and driver families"

test_tmp=$(mktemp -d)
trap 'rm -rf "$test_tmp"' EXIT

catalog="$test_tmp/enclosures.tsv"
bus="$test_tmp/thunderbolt"
device="$test_tmp/devices/0-1"
mkdir -p "$bus/domain0" "$device"
printf 'user\n' >"$bus/domain0/security"
printf '0x41\n' >"$device/vendor"
printf '0x308\n' >"$device/device"
printf '0\n' >"$device/authorized"
cp "$enclosures" "$catalog"

OMARCHY_EGPU_ENCLOSURE_CATALOG="$catalog" \
  OMARCHY_THUNDERBOLT_SYSFS="$bus" \
  "$authorize" "$device"
[[ $(<"$device/authorized") == "1" ]] || fail "a catalogued enclosure is automatically authorized"
pass "a catalogued enclosure is automatically authorized"

printf '0\n' >"$device/authorized"
rm "$bus/domain0/security"
OMARCHY_EGPU_ENCLOSURE_CATALOG="$catalog" \
  OMARCHY_THUNDERBOLT_SYSFS="$bus" \
  "$authorize" "$device"
[[ $(<"$device/authorized") == "0" ]] || fail "missing Thunderbolt security state fails closed"

printf 'user\n' >"$bus/domain0/security"
chmod 000 "$bus/domain0/security"
OMARCHY_EGPU_ENCLOSURE_CATALOG="$catalog" \
  OMARCHY_THUNDERBOLT_SYSFS="$bus" \
  "$authorize" "$device"
[[ $(<"$device/authorized") == "0" ]] || fail "unreadable Thunderbolt security state fails closed"
chmod 600 "$bus/domain0/security"
pass "authorization requires readable Thunderbolt security state"

printf '0\n' >"$device/authorized"
printf '0x9999\n' >"$device/device"
OMARCHY_EGPU_ENCLOSURE_CATALOG="$catalog" \
  OMARCHY_THUNDERBOLT_SYSFS="$bus" \
  "$authorize" "$device"
[[ $(<"$device/authorized") == "0" ]] || fail "an unknown Thunderbolt device remains unauthorized"
pass "an unknown Thunderbolt device remains unauthorized"

printf '0x308\n' >"$device/device"
printf 'secure\n' >"$bus/domain0/security"
OMARCHY_EGPU_ENCLOSURE_CATALOG="$catalog" \
  OMARCHY_THUNDERBOLT_SYSFS="$bus" \
  "$authorize" "$device"
[[ $(<"$device/authorized") == "0" ]] || fail "secure-mode enrollment is not bypassed"
pass "secure-mode enrollment is not bypassed"

printf 'none\n' >"$bus/domain0/security"
OMARCHY_EGPU_ENCLOSURE_CATALOG="$catalog" \
  OMARCHY_THUNDERBOLT_SYSFS="$bus" \
  "$authorize" "$device"
[[ $(<"$device/authorized") == "1" ]] || fail "explicitly permitted none-mode authorization is allowed"
pass "only explicitly permitted Thunderbolt security modes authorize directly"

grep -Fq 'SUBSYSTEM=="thunderbolt"' "$rule" || fail "the udev rule is scoped to Thunderbolt"
grep -Fq 'ATTR{authorized}=="0"' "$rule" || fail "the udev rule only handles unauthorized devices"
grep -Fq '/usr/bin/omarchy-hw-egpu-authorize /sys%p' "$rule" ||
  fail "the udev rule delegates to the packaged allowlist helper"
pass "the udev rule is narrow and uses the packaged helper"

stub_bin="$test_tmp/bin"
calls="$test_tmp/calls"
limine_conf="$test_tmp/t2-mac.conf"
running_cmdline="$test_tmp/cmdline"
rule_target="$test_tmp/90-omarchy-egpu.rules"
repair_marker="$test_tmp/repaired"
legacy_limine_conf="$test_tmp/egpu-hotplug.conf"
mkdir -p "$stub_bin"
: >"$calls"

cat >"$stub_bin/sudo" <<'SH'
#!/bin/bash
printf '%s\n' "$*" >>"$TEST_LOG"
"$@"
SH
cat >"$stub_bin/lspci" <<'SH'
#!/bin/bash
echo '0000:01:00.0 0680: 106b:1801'
SH
cat >"$stub_bin/limine-mkinitcpio" <<'SH'
#!/bin/bash
echo limine-mkinitcpio >>"$TEST_LOG"
SH
chmod +x "$stub_bin"/*

cat >"$limine_conf" <<'EOF'
# Generated by Omarchy installer for T2 Mac support
KERNEL_CMDLINE[default]+=" intel_iommu=on iommu=pt pm_async=off mem_sleep_default=deep"
EOF
printf 'quiet splash\n' >"$running_cmdline"
cat >"$legacy_limine_conf" <<'EOF'
# Reserve enough prefetchable PCIe address space for a hot-plugged eGPU.
KERNEL_CMDLINE[default]+=" pci=realloc,hpmmioprefsize=512M"
EOF

PATH="$stub_bin:$PATH" TEST_LOG="$calls" OMARCHY_PATH="$ROOT" \
  OMARCHY_EGPU_UDEV_RULE="$rule_target" \
  OMARCHY_EGPU_UDEV_CONTROL="$test_tmp/no-udevd" \
  OMARCHY_T2_LIMINE_CONF="$limine_conf" \
  OMARCHY_EGPU_LEGACY_LIMINE_CONF="$legacy_limine_conf" \
  OMARCHY_T2_RUNNING_CMDLINE="$running_cmdline" \
  OMARCHY_EGPU_REPAIR_MARKER="$repair_marker" \
  bash -euo pipefail "$migration" >/dev/null

cmp -s "$rule" "$rule_target" || fail "the migration installs the packaged udev rule"
grep -Fq 'pci=realloc,hpmmioprefsize=512M' "$limine_conf" ||
  fail "the migration reserves the T2 PCI hot-plug window"
grep -Fxq 'limine-mkinitcpio' "$calls" || fail "the migration rebuilds the T2 boot image"
[[ -f $repair_marker ]] || fail "the migration records its machine-wide rebuild"
[[ ! -e $legacy_limine_conf ]] || fail "the migration folds the exact live-test drop-in into T2 configuration"
pass "existing T2 installs gain authorization and PCI hot-plug support"

: >"$calls"
PATH="$stub_bin:$PATH" TEST_LOG="$calls" OMARCHY_PATH="$ROOT" \
  OMARCHY_EGPU_UDEV_RULE="$rule_target" \
  OMARCHY_EGPU_UDEV_CONTROL="$test_tmp/no-udevd" \
  OMARCHY_T2_LIMINE_CONF="$limine_conf" \
  OMARCHY_EGPU_LEGACY_LIMINE_CONF="$legacy_limine_conf" \
  OMARCHY_T2_RUNNING_CMDLINE="$running_cmdline" \
  OMARCHY_EGPU_REPAIR_MARKER="$repair_marker" \
  bash -euo pipefail "$migration" >/dev/null

[[ ! -s $calls ]] || fail "the eGPU migration remains machine-idempotent" "$(cat "$calls")"
(( $(grep -o 'pci=realloc,hpmmioprefsize=512M' "$limine_conf" | wc -l) == 1 )) ||
  fail "the T2 resource parameter is not duplicated"
pass "the eGPU migration remains machine-idempotent"

rm -f "$limine_conf"
cat >"$legacy_limine_conf" <<'EOF'
KERNEL_CMDLINE[default]+=" pci=realloc,hpmmioprefsize=512M"
EOF
PATH="$stub_bin:$PATH" TEST_LOG="$calls" OMARCHY_PATH="$ROOT" \
  OMARCHY_EGPU_UDEV_RULE="$rule_target" OMARCHY_EGPU_UDEV_CONTROL="$test_tmp/no-udevd" \
  OMARCHY_T2_LIMINE_CONF="$limine_conf" OMARCHY_EGPU_LEGACY_LIMINE_CONF="$legacy_limine_conf" \
  OMARCHY_T2_RUNNING_CMDLINE="$running_cmdline" OMARCHY_EGPU_REPAIR_MARKER="$repair_marker" \
  bash -euo pipefail "$migration" >/dev/null
[[ -f $legacy_limine_conf ]] || fail "the legacy BAR drop-in survives when maintained T2 config is missing"
pass "legacy BAR configuration is retained until maintained configuration is verified"

cat >"$limine_conf" <<'EOF'
# KERNEL_CMDLINE[default]+=" pci=realloc,hpmmioprefsize=512M"
NOTE="pci=realloc,hpmmioprefsize=512M"
EOF
if PATH="$stub_bin:$PATH" TEST_LOG="$calls" OMARCHY_PATH="$ROOT" \
  OMARCHY_EGPU_UDEV_RULE="$rule_target" OMARCHY_EGPU_UDEV_CONTROL="$test_tmp/no-udevd" \
  OMARCHY_T2_LIMINE_CONF="$limine_conf" OMARCHY_EGPU_LEGACY_LIMINE_CONF="$legacy_limine_conf" \
  OMARCHY_T2_RUNNING_CMDLINE="$running_cmdline" OMARCHY_EGPU_REPAIR_MARKER="$repair_marker" \
  bash -euo pipefail "$migration" >/dev/null 2>&1; then
  fail "comments and arbitrary text do not verify maintained kernel configuration"
fi
[[ -f $legacy_limine_conf ]] || fail "failed positive verification retains the legacy BAR drop-in"
pass "only an active KERNEL_CMDLINE assignment verifies the maintained BAR parameter"

grep -Fq 'pci=realloc,hpmmioprefsize=512M' "$ROOT/install/hardware/apple/fix-t2.sh" ||
  fail "fresh T2 installs reserve the PCI hot-plug window"
grep -Fq 'hardware/egpu.sh' "$ROOT/install/hardware/all.sh" ||
  fail "fresh installs run generic eGPU setup"
grep -Fxq 'ggml-vulkan' "$ROOT/install/omarchy-other.packages" ||
  fail "fresh media includes the modular llama.cpp Vulkan backend"
grep -Fq 'omarchy-pkg-add ggml-vulkan' "$ROOT/install/hardware/egpu.sh" ||
  fail "fresh installs enable llama.cpp GPU support"
grep -Fq 'LLAMA_ARG_MODELS_PRESET=%h/.config/omarchy/egpu/llama-models.ini' \
  "$ROOT/default/systemd/user/mia-local-llm.service.d/20-omarchy-gpu-placement.conf" ||
  fail "the model router consumes the OS-managed per-model preset"
pass "fresh installs enable generic eGPU support"
